"""Общие контракты для модулей."""
from typing import Protocol, Optional, List, Any

class UserRepositoryContract(Protocol):
    def get_by_id(self, user_id: int) -> Optional[Any]: ...
    def get_role(self, user_id: int) -> str: ...

class ProjectRepositoryContract(Protocol):
    def get_by_id(self, project_id: int) -> Optional[Any]: ...
    def get_active_projects(self) -> List[Any]: ...
